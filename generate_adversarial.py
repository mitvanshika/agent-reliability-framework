"""
Generates a universal adversarial scenario suite for any target.

    python generate_adversarial.py <target> [--force]

Fills the generic attack templates in adversarial/templates.yaml with the
target's description from targets.yaml (deterministic, no LLM, no API
call) and writes scenarios_adversarial/<target>/adv_<kind>.yaml.

These scenarios are a SEPARATE suite: they are never added to scenarios/
and never change the main baseline. Run them with:

    python run_experiment.py experiments/<name>.yaml --scenario-dir scenarios_adversarial/<target>

Re-running produces byte-identical files. A file that was edited by hand is
not overwritten unless --force.
"""

import argparse
import json
import os
import re
import sys

import yaml

import run_suite

REPO_DIR = os.path.dirname(os.path.abspath(__file__))
TEMPLATES_FILE = os.path.join(REPO_DIR, "adversarial", "templates.yaml")
OUT_ROOT = "scenarios_adversarial"


def load_templates(path=None):
    with open(path or TEMPLATES_FILE, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    return data["templates"]


def _words(text):
    return set(re.findall(r"[a-z0-9]+", text.lower()))


def _question(template, description):
    if "question" in template:
        return template["question"]
    if "question_repeat" in template:
        r = template["question_repeat"]
        return r["text"] * int(r["times"]) + r.get("then", "")
    words = _words(description)
    for cand in template["question_candidates"]:
        if not words & {w.lower() for w in cand.get("unless_description_mentions", [])}:
            return cand["question"]
    raise ValueError(f"every out-of-scope candidate overlaps the description '{description}': "
                     "add a candidate to adversarial/templates.yaml")


def build(description, templates=None):
    """[(scenario_id, yaml_text)] for this description, in template order."""
    if not (description or "").strip():
        raise ValueError("the target needs a description in targets.yaml (one line about what it is for)")
    description = description.strip()
    out = []
    for t in templates or load_templates():
        sid = f"adv_{t['kind']}"
        question = _question(t, description)
        answer = t["expected_answer"].replace("{description}", description)
        text = (f"# generated by generate_adversarial.py from adversarial/templates.yaml; re-generate, don't edit\n"
                f"id: {json.dumps(sid)}\n"
                f"question: {json.dumps(question, ensure_ascii=False)}\n"
                f"category: \"adversarial\"\n"
                f"attack: {json.dumps(t['kind'])}\n"
                f"expected_answer: {json.dumps(answer, ensure_ascii=False)}\n")
        out.append((sid, text))
    return out


def main(argv=None):
    p = argparse.ArgumentParser(description="Generate the universal adversarial suite for a target.")
    p.add_argument("target")
    p.add_argument("--force", action="store_true", help="overwrite files that were edited by hand")
    p.add_argument("--out-root", default=OUT_ROOT)
    args = p.parse_args(argv)

    targets = run_suite.load_targets()
    if args.target not in targets:
        sys.exit(f"'{args.target}' is not in {run_suite.TARGETS_FILE}. Found: {list(targets)}")
    try:
        scenarios = build(targets[args.target].get("description"))
    except ValueError as e:
        sys.exit(f"{args.target}: {e}")

    out_dir = os.path.join(args.out_root, args.target)
    os.makedirs(out_dir, exist_ok=True)
    changed = []
    for sid, text in scenarios:
        path = os.path.join(out_dir, f"{sid}.yaml")
        data = text.replace("\n", "\r\n").encode("utf-8")
        if os.path.isfile(path) and open(path, "rb").read() != data and not args.force:
            changed.append(path)
            continue
        open(path, "wb").write(data)
    if changed:
        sys.exit("Not overwritten (edited by hand?): " + ", ".join(changed) + ". Use --force to regenerate them.")
    print(f"Wrote {len(scenarios)} adversarial scenarios to {out_dir}/")
    return out_dir


if __name__ == "__main__":
    main()
